const languageMap = { 'en-US': 'en', de: 'de', pl: 'pl', ko: 'ko', nl: 'nl' };

export function languageCode(value) {
  return languageMap[value] || 'en';
}

export function applyLanguage(value, root = document) {
  const language = languageCode(value);
  const dictionary = translations[language] || translations.en;
  if (root.documentElement) root.documentElement.lang = language;
  root.querySelectorAll('[data-i18n]').forEach((element) => {
    const text =
      dictionary[element.dataset.i18n] || translations.en[element.dataset.i18n];
    if (text) element.textContent = text;
  });
  root.querySelectorAll('[data-i18n-html]').forEach((element) => {
    const html =
      dictionary[element.dataset.i18nHtml] || translations.en[element.dataset.i18nHtml];
    if (html) element.innerHTML = html;
  });
  for (const [dataName, attribute] of [
    ['i18nAlt', 'alt'],
    ['i18nAriaLabel', 'aria-label'],
    ['i18nPlaceholder', 'placeholder'],
    ['i18nTitle', 'title'],
  ]) {
    root
      .querySelectorAll(`[data-${dataName.replace(/[A-Z]/g, '-$&').toLowerCase()}]`)
      .forEach((element) => {
        const text =
          dictionary[element.dataset[dataName]] ||
          translations.en[element.dataset[dataName]];
        if (text) element.setAttribute(attribute, text);
      });
  }
  if (typeof root.dispatchEvent === 'function' && typeof CustomEvent !== 'undefined') {
    root.dispatchEvent(new CustomEvent('language:changed', { detail: { language } }));
  }
}
